export function isWall(x, y) {
    let gridX = Math.round(x);
    let gridY = Math.round(y);
    if (gridX < 0 || gridX >= map[0].length || gridY < 0 || gridY >= map.length) return true;
    return map[gridY][gridX] === 1;
}